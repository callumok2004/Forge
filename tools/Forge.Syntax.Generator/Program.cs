using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

using Forge.Syntax.TextMate;

if (args.Length < 3) {
	Console.Error.WriteLine("usage: <grammars dir> <output .cs> <grammar>...");
	return 1;
}

SortedSet<string> translated = new(StringComparer.Ordinal);

foreach (string name in args[2..]) {
	using JsonDocument grammar = JsonDocument.Parse(File.ReadAllText(Path.Combine(args[0], name + ".tmLanguage.json")), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true });
	Collect(grammar.RootElement, translated);
}

StringBuilder source = new();
source.AppendLine("// <auto-generated/>");
source.AppendLine("#nullable enable");
source.AppendLine("using System.Collections.Frozen;");
source.AppendLine("using System.Text.RegularExpressions;");
source.AppendLine();
source.AppendLine("namespace Forge.Syntax.TextMate;");
source.AppendLine();
source.AppendLine("internal static partial class BundledRegexes");
source.AppendLine("{");
source.AppendLine("\tprivate const RegexOptions Options = RegexOptions.Multiline | RegexOptions.CultureInvariant;");
source.AppendLine();
source.AppendLine("\tprivate static readonly System.Collections.Frozen.FrozenDictionary<string, System.Func<Regex>> Table = new System.Collections.Generic.Dictionary<string, System.Func<Regex>>(System.StringComparer.Ordinal) {");

int index = 0;

foreach (string pattern in translated) source.AppendLine($"\t\t[{Literal(pattern)}] = P{index++},");

source.AppendLine("\t}.ToFrozenDictionary(System.StringComparer.Ordinal);");
source.AppendLine();
source.AppendLine("\tstatic partial void Find(string translated, ref Regex? regex) {");
source.AppendLine("\t\tif (Table.TryGetValue(translated, out System.Func<Regex>? factory)) regex = factory();");
source.AppendLine("\t}");

index = 0;

foreach (string pattern in translated) {
	source.AppendLine();
	source.AppendLine($"\t[GeneratedRegex({Literal(pattern)}, Options)]");
	source.AppendLine($"\tprivate static partial Regex P{index++}();");
}

source.AppendLine("}");

string output = source.ToString();

if (!File.Exists(args[1]) || File.ReadAllText(args[1]) != output) {
	Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[1]))!);
	File.WriteAllText(args[1], output);
}

Console.WriteLine($"{translated.Count} bundled grammar regexes");
return 0;

static void Collect(JsonElement element, SortedSet<string> into) {
	switch (element.ValueKind) {
		case JsonValueKind.Object:
			foreach (JsonProperty property in element.EnumerateObject()) {
				if (property.Value.ValueKind == JsonValueKind.String && property.Name is "match" or "begin" or "end" or "while") Add(property.Name, property.Value.GetString()!, into);
				else Collect(property.Value, into);
			}

			break;

		case JsonValueKind.Array:
			foreach (JsonElement item in element.EnumerateArray()) Collect(item, into);

			break;
	}
}

static void Add(string key, string pattern, SortedSet<string> into) {
	if (key is "end" or "while" && Regex.IsMatch(pattern, @"\\\d")) return;

	string translated = OnigTranslate.Translate(pattern);

	try {
		_ = new Regex(translated, RegexOptions.Multiline | RegexOptions.CultureInvariant);
		into.Add(translated);
	}
	catch (ArgumentException) {
	}
}

static string Literal(string value) => "@\"" + value.Replace("\"", "\"\"") + "\"";
